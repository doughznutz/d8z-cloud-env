// LocalService is one of the root project's own long-running non-gateway
// services: the dev tools (deightz, the ollama gateway, gopher, the otel
// collector). The deploy tooling isn't here - it's one-shot jobs (jobs.go).
// Unlike a gateway, these live in our own compose project (selfProject) and
// are plain start/stop, no nesting.
type LocalService struct {
	Name          string `json:"name"`
	Label         string `json:"label"`
	Profile       string `json:"profile"`
	BundleProfile string `json:"-"` // its profile in bundle/compose.yaml (child gateways)
}

var localServices = []LocalService{
	{Name: "deightz", Label: "Deightz IDE", Profile: "local", BundleProfile: "deightz"},
	{Name: "ollama-gatewai", Label: "Ollama gateway", Profile: "local", BundleProfile: "og"},
	{Name: "gopher", Label: "Gopher test runner", Profile: "local", BundleProfile: "gopher"},
	{Name: "otel-collector", Label: "OTel collector", Profile: "local", BundleProfile: "otel"},
}

func localService(name string) (LocalService, bool) {
	for _, s := range localServices {
		if s.Name == name {
			return s, true
		}
	}
	return LocalService{}, false
}

// StartLocal brings up a local service. On the root it comes from the root
// docker-compose.yaml; in a child gateway from the bundle file it was spawned
// from (the root file's fixed container names would collide with the
// root's). In a workspace gateway, Deightz always gets that workspace
// mounted - the same mount the gateway's own gw-server has.
//
// project, if non-empty and not "self", is a legacy projects-root directory
// to open in Deightz instead (PROJECT for this invocation only).
func (m *Manager) StartLocal(name, project string) error {
	svc, ok := localService(name)
	if !ok {
		return fmt.Errorf("unknown service %q", name)
	}
	var projectEnv []string
	if project != "" && project != "self" && m.cfg.WorkspaceName == "" {
		if err := safeProjectName(project); err != nil {
			return err
		}
		projectEnv = []string{"PROJECT=" + project}
	}
	files, err := m.localComposeFiles(svc)
	if err != nil {
		return err
	}
	if m.cfg.WorkspaceName != "" && m.assignment() == nil {
		return fmt.Errorf("waiting for workspace %q's assignment from the parent gateway", m.cfg.WorkspaceName)
	}
	if a := m.assignment(); a != nil {
		projectEnv = []string{"PROJECT=" + wsMountName(a.Workspace)}
		if svc.Name == "deightz" {
			var b bytes.Buffer
			b.WriteString("# Generated by gw-server - do not edit.\nservices:\n  deightz:\n    environment:\n      GITHUB_TOKEN: \"\"\n    volumes: !override\n      - /var/run/docker.sock:/var/run/docker.sock\n")
			writeMount(&b, a.Mount)
			writeExternalVolume(&b, a.Mount)
			f := filepath.Join(m.cfg.StateDir, "local-deightz.override.yaml")
			if err := os.MkdirAll(m.cfg.StateDir, 0o755); err != nil {
				return err
			}
			if err := os.WriteFile(f, b.Bytes(), 0o644); err != nil {
				return err
			}
			files = append(files, "-f", f)
		}
	}
	o, err := m.projectOp("svc:"+name, "starting", "building / pulling images and starting "+name)
	if err != nil {
		return err
	}
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Minute)
		defer cancel()
		m.finishProject("svc:"+name, o, m.runLocal(ctx, func(project string) error {
			args := append(append([]string{"compose", "-p", project}, files...), "up", "-d", "--build", svc.Name)
			return upWithRetryEnv(ctx, o.Log, "", projectEnv, args)
		}))
	}()
	return nil
}

// localComposeFiles are the compose arguments (files and profile) a local
// service is managed with on this gateway.
func (m *Manager) localComposeFiles(svc LocalService) ([]string, error) {
	if m.cfg.Role == "child" {
		return []string{"--env-file", m.cfg.EnvFile, "-f", m.cfg.BundleFile, "--profile", svc.BundleProfile}, nil
	}
	return []string{"-f", m.cfg.RootComposeFile, "--profile", svc.Profile}, nil
}

func (m *Manager) StopLocal(name string) error {
	svc, ok := localService(name)
	if !ok {
		return fmt.Errorf("unknown service %q", name)
	}
	o, err := m.projectOp("svc:"+name, "stopping", "stopping "+name)
	if err != nil {
		return err
	}
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		defer cancel()
		m.finishProject("svc:"+name, o, m.runLocal(ctx, func(project string) error {
			files, _ := m.localComposeFiles(svc)
			args := append(append([]string{"compose", "-p", project}, files...), "stop", svc.Name)
			return dockerStreamHost(ctx, o.Log, "", args...)
		}))
	}()
	return nil
}

func (m *Manager) runLocal(ctx context.Context, fn func(project string) error) error {
	project := m.selfProject(ctx)
	if project == "" {
		return fmt.Errorf("can't determine our own compose project")
	}
	return fn(project)
}

// LocalOps reports in-flight start/stop state for local services, by their
// plain name (without the "svc:" op-map prefix), so /api/self can surface
// "starting"/"stopping"/"error" before (or without) a container to show it.
func (m *Manager) LocalOps() map[string]map[string]string {
	m.mu.Lock()
	defer m.mu.Unlock()
	out := map[string]map[string]string{}
	for key, o := range m.projOps {
		name, ok := strings.CutPrefix(key, "svc:")
		if !ok {
			continue
		}
		v := map[string]string{"state": o.State}
		if o.Phase != "" {
			v["phase"] = o.Phase
		}
		if o.Err != "" {
			v["error"] = o.Err
		}
		out[name] = v
	}
	return out
}
