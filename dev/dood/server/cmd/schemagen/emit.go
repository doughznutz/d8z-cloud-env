package main

// Emitting a structType as JSON Schema and as a TypeScript interface, from
// the same in-memory model, so the two outputs can't drift relative to
// each other even though they're written as separate files.

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// schemaDoc is one type's JSON Schema document (draft 2020-12).
type schemaDoc struct {
	Schema               string         `json:"$schema"`
	ID                   string         `json:"$id"`
	Title                string         `json:"title"`
	Description          string         `json:"description,omitempty"`
	Type                 string         `json:"type"`
	Properties           map[string]any `json:"properties"`
	Required             []string       `json:"required,omitempty"`
	AdditionalProperties bool           `json:"additionalProperties"`
}

// schemaFor renders st as a JSON Schema document. A kindRef field points
// at the referenced type's own schema file by name.
func schemaFor(st structType) schemaDoc {
	props := map[string]any{}
	var required []string
	for _, f := range st.fields {
		p := schemaType(f.typ)
		if f.doc != "" {
			p["description"] = f.doc
		}
		props[f.jsonName] = p
		if !f.optional {
			required = append(required, f.jsonName)
		}
	}
	sort.Strings(required)
	return schemaDoc{
		Schema: "https://json-schema.org/draft/2020-12/schema",
		ID:     st.name + ".schema.json", Title: st.name, Description: st.doc,
		Type: "object", Properties: props, Required: required, AdditionalProperties: false,
	}
}

// schemaType renders one field's (or element's) type as a JSON Schema
// fragment.
func schemaType(t fieldType) map[string]any {
	switch t.kind {
	case kindString:
		return map[string]any{"type": "string"}
	case kindBool:
		return map[string]any{"type": "boolean"}
	case kindInt:
		return map[string]any{"type": "integer"}
	case kindFloat:
		return map[string]any{"type": "number"}
	case kindTime:
		return map[string]any{"type": "string", "format": "date-time"}
	case kindSlice:
		return map[string]any{"type": "array", "items": schemaType(*t.elem)}
	case kindMap:
		return map[string]any{"type": "object", "additionalProperties": schemaType(*t.elem)}
	case kindRef:
		return map[string]any{"$ref": t.ref + ".schema.json"}
	default: // kindAny
		return map[string]any{}
	}
}

// marshalSchema is doc as indented JSON, newline-terminated, with <, > and
// & left unescaped - it's a file on disk, not HTML.
func marshalSchema(doc schemaDoc) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// tsHeader is written at the top of the generated TypeScript file.
const tsHeader = `// Generated by schemagen (go generate ./...) from the Go structs that
// define gw-server's JSON wire format - do not edit by hand.
`

// renderTS renders every type in types as one TypeScript module.
func renderTS(types []structType) string {
	var b strings.Builder
	b.WriteString(tsHeader)
	for _, st := range types {
		b.WriteString("\n")
		if st.doc != "" {
			writeTSDoc(&b, "", st.doc)
		}
		fmt.Fprintf(&b, "export interface %s {\n", st.name)
		for _, f := range st.fields {
			if f.doc != "" {
				writeTSDoc(&b, "  ", f.doc)
			}
			opt := ""
			if f.optional {
				opt = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", f.jsonName, opt, tsType(f.typ))
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// tsType renders one field's (or element's) type as a TypeScript type.
func tsType(t fieldType) string {
	switch t.kind {
	case kindString, kindTime:
		return "string"
	case kindBool:
		return "boolean"
	case kindInt, kindFloat:
		return "number"
	case kindSlice:
		return tsType(*t.elem) + "[]"
	case kindMap:
		return "Record<string, " + tsType(*t.elem) + ">"
	case kindRef:
		return t.ref
	default: // kindAny
		return "unknown"
	}
}

// writeTSDoc writes doc as a "/** ... */" TSDoc comment, indented by
// prefix, one line if it fits on one, else a wrapped block.
func writeTSDoc(b *strings.Builder, prefix, doc string) {
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", prefix, lines[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", prefix)
	for _, l := range lines {
		fmt.Fprintf(b, "%s * %s\n", prefix, l)
	}
	fmt.Fprintf(b, "%s */\n", prefix)
}
