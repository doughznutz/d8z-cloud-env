package main

import (
	"fmt"
	"net/http"
	"strings"

	"gopkg.in/yaml.v3"
)

// ----- YAML struct definitions -----
type AssistantConfig struct {
	Name    string           `yaml:"name"`
	Version string           `yaml:"version"`
	Schema  string           `yaml:"schema"`
	Models  []AssistantModel `yaml:"models"`
}

type AssistantModel struct {
	Name                     string             `yaml:"name"`
	Provider                 string             `yaml:"provider"`
	APIBase                  string             `yaml:"apiBase"`
	Model                    string             `yaml:"model"`
	Capabilities             []string           `yaml:"capabilities,omitempty"`
	Roles                    []string           `yaml:"roles"`
	DefaultCompletionOptions *CompletionOptions `yaml:"defaultCompletionOptions,omitempty"`
}

type CompletionOptions struct {
	Temperature float64 `yaml:"temperature"`
	MaxTokens   int     `yaml:"maxTokens"`
}

// ----- Config builder -----
func getAsistantModels() []AssistantModel {
	var models []AssistantModel
	for _, provider := range ogProviders {
		if provider.APIKey != "" {
			// Determine the 'provider' field for Continue.
			// OpenAI-compatible ones can use 'openai'. Gemini needs 'gemini'.
			var continueProvider string
			var modelName string
			if provider.Name == "Gemini" {
				continueProvider = "gemini"
				modelName = provider.Models[0] // e.g., "gemini-2.5-flash"
			} else {
				continueProvider = "openai"
				// For Continue, the 'model' field should be the provider name
				// so that when we get the request, we know which provider it is.
				modelName = provider.Name
			}

			models = append(models,
				AssistantModel{
					Name:     provider.Name,
					Model:    modelName,
					Provider: continueProvider,
					APIBase:  fmt.Sprintf("http://og:11434%s", provider.APIBase),
					// TODO: Fix these based on provider capabilities.
					Capabilities: []string{"tool_use", "image_input"},
					Roles:        []string{"chat", "edit", "apply"},
					DefaultCompletionOptions: &CompletionOptions{
						Temperature: 0.7,
						MaxTokens:   1500,
					},
				},
			)
		}
	}
	return models
}

// ----- Handler for YAML -----
func handleContinueYaml(w http.ResponseWriter, r *http.Request) {
	out, err := yaml.Marshal(
		AssistantConfig{
			Name:    "ollama-gatewai",
			Version: "0.0.1",
			Schema:  "v1",
			Models:  getAsistantModels(),
		},
	)
	if err != nil {
		http.Error(w, fmt.Sprintf("yaml marshal error: %v", err), http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/x-yaml")
	w.Write([]byte(strings.Join([]string{
		"# DO NOT EDIT: This file is generated by:\n",
		"# curl http://og:11434/continue-yaml > ",
		"~/.continue/assistants/OG-Assistants.yaml\n",
	},"")))
	w.Write(out)
}
